/**
 * 업무용 말투로 바꾼다('~해요' → '~합니다').
 * 화면 파일의 고정 문구는 한 번 일괄 변환했고, 서비스(src/)에서 오는 문장은 화면에 그릴 때 이 함수를 거친다.
 */
const RULES: [RegExp, string][] = [
  [/하시겠어요/g, '하시겠습니까'],
  [/([가-힣])세요(?![가-힣])/g, '$1십시오'],
  [/눌러요(?![가-힣])/g, '누릅니다'],
  [/달라요(?![가-힣])/g, '다릅니다'],
  [/같아요(?![가-힣])/g, '같습니다'],
  [/하나요(?![가-힣])/g, '합니까'],
  [/인가요(?![가-힣])/g, '입니까'],
  [/([가-힣])나요(?![가-힣])/g, '$1습니까'],
  [/([가-힣])(?:어|아)요(?![가-힣])/g, '$1습니다'],
  [/해요(?![가-힣])/g, '합니다'],
  [/돼요(?![가-힣])/g, '됩니다'],
  [/이에요(?![가-힣])/g, '입니다'],
  [/예요(?![가-힣])/g, '입니다'],
];

export function formal(text: string): string {
  return RULES.reduce((s, [re, to]) => s.replace(re, to), text);
}
